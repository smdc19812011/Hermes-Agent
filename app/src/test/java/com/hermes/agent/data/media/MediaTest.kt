class MediaTest {

    @Test
    fun sniffsCommonFormats() {
        assertEquals("image/png", Mime.sniff(byteArrayOf(0x89.toByte(), 0x50, 0x4E, 0x47, 0x0D, 0x0A)))
        assertEquals("image/jpeg", Mime.sniff(byteArrayOf(0xFF.toByte(), 0xD8.toByte(), 0xFF.toByte(), 0xE0.toByte())))
        assertEquals("image/webp", Mime.sniff("RIFF\u0000\u0000\u0000\u0000WEBPVP8 ".toByteArray()))
        assertEquals("audio/wav", Mime.sniff("RIFF\u0000\u0000\u0000\u0000WAVEfmt ".toByteArray()))
        assertEquals("video/mp4", Mime.sniff("\u0000\u0000\u0000\u0018ftypisom".toByteArray()))
        assertEquals("audio/mpeg", Mime.sniff("ID3\u0004".toByteArray()))
        assertEquals("application/pdf", Mime.sniff("%PDF-1.7".toByteArray()))
        assertNull(Mime.sniff("hello".toByteArray()))
        // A server's octet-stream loses to content; an unknown body falls back to the extension.
        assertEquals("image/png", Mime.resolve("application/octet-stream", "x.bin", byteArrayOf(0x89.toByte(), 0x50, 0x4E, 0x47)))
        assertEquals("text/csv", Mime.resolve(null, "data.csv", "a,b".toByteArray()))
    }

    @Test
    fun attachmentsRoundTrip() {
        val list = listOf(Attachment("a.png", "image/png", "attachments/c/a.png", 10, "Generated by x"), Attachment("r", "image/*", "https://e.com/r.jpg"))
        assertEquals(list, Attachment.decode(Attachment.encode(list)))
        assertNull(Attachment.encode(emptyList()))
        assertEquals(emptyList<Attachment>(), Attachment.decode("not json"))
        assertTrue(list[1].isRemote)
        assertEquals(Attachment.Kind.IMAGE, list[1].kind)
    }

    @Test
    fun findsImageLinksInReplies() {
        val text = """Here: ![statue](https://upload.wikimedia.org/a/b/Hermes.jpg) and https://cdn.example.com/img/cat.PNG?w=400.
            |Not this: https://example.com/page.html or (https://x.com/y.jpg is in parens but still an image).""".trimMargin()
        val links = imageLinks(text)
        assertEquals("https://upload.wikimedia.org/a/b/Hermes.jpg", links[0])
        assertTrue(links.contains("https://cdn.example.com/img/cat.PNG?w=400"))
        assertTrue(links.none { it.endsWith(".html") })
    }

    @Test
    fun decodesDataUrls() {
        val (bytes, mime) = MediaGenerator.decodeDataUrl("data:image/png;base64," + Base64.getEncoder().encodeToString(byteArrayOf(1, 2, 3)))!!
        assertArrayEquals(byteArrayOf(1, 2, 3), bytes)
        assertEquals("image/png", mime)
        assertNull(MediaGenerator.decodeDataUrl("https://example.com/a.png"))
    }

    @Test
    fun parsesImageSearchResults() {
        val ov = ImageSearchTool.parseOpenverse(javaClass.classLoader!!.getResource("openverse-images.json")!!.readText())
        assertEquals(3, ov.size)
        assertTrue(ov.all { it.url.startsWith("https://") && it.license.startsWith("CC") })
        val wm = ImageSearchTool.parseWikimedia(javaClass.classLoader!!.getResource("wikimedia-images.json")!!.readText())
        assertTrue(wm.isNotEmpty())
        assertTrue(wm.all { it.url.startsWith("https://upload.wikimedia.org/") && it.thumbnail != null })
        assertTrue(wm.any { it.license.contains("Public domain", ignoreCase = true) || it.license.isNotBlank() })
    }

    /** Runs the exact Termux chunk script through bash and reassembles the file like AttachmentStore does. */
    @Test
    fun termuxChunkedCopyReassemblesExactly() {
        val home = Files.createTempDirectory("media-home").toFile()
        val payload = ByteArray(TERMUX_CHUNK_BYTES * 2 + 1234) { (it * 31 % 251).toByte() }
        File(home, "my clip's.mp4").writeBytes(payload)
        val q = MediaScripts.quotePath("~/my clip's.mp4")
        val size = bash(home, MediaScripts.size(q)).trim().toLong()
        assertEquals(payload.size.toLong(), size)
        val out = java.io.ByteArrayOutputStream()
        var i = 0L
        while (out.size() < size) {
            val chunk = bash(home, MediaScripts.chunk(q, i++, TERMUX_CHUNK_BYTES)).trim()
            assertTrue("chunk stays under Termux's 100 KB result limit", chunk.length < 100 * 1024)
            out.write(Base64.getDecoder().decode(chunk))
        }
        assertArrayEquals(payload, out.toByteArray())
        assertEquals("", bash(home, MediaScripts.size(MediaScripts.quotePath("~/missing.mp4"))))
    }

    @Test
    fun espeakScriptReportsMissingBinary() {
        val home = Files.createTempDirectory("media-home").toFile()
        val p = ProcessBuilder("bash").directory(home).apply {
            environment()["HOME"] = home.absolutePath
            environment()["PATH"] = "/nonexistent"
        }.start()
        p.outputStream.use { it.write(HermesScripts.wrapForStdin(MediaScripts.espeak("hi; rm -rf /", "en-us", "~/s.wav")).toByteArray()) }
        p.waitFor(10, TimeUnit.SECONDS)
        assertEquals(127, p.exitValue())
    }

    private fun bash(home: File, script: String): String {
        val p = ProcessBuilder("bash").directory(home).apply { environment()["HOME"] = home.absolutePath }.start()
        p.outputStream.use { it.write(HermesScripts.wrapForStdin(script).toByteArray()) }
        val out = p.inputStream.bufferedReader().readText()
        p.waitFor(20, TimeUnit.SECONDS)
        return out
    }
}
